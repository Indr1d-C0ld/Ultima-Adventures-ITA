using System;
using Server;
using Server.Mobiles;
using Server.OneTime.Events;
using Server.Regions;

namespace Server.Items
{
	public class BloodRune : Item
	{
		private const int BaseCooldownMinutes = 30;
		private const int CooldownUpgradeMinutes = 5;
		private const int MinimumCooldownMinutes = 10;
		private const int MaximumUpgradeLevel = (BaseCooldownMinutes - MinimumCooldownMinutes) / CooldownUpgradeMinutes;
		public const int SoulForceUpgradeCost = 2500;
		private const int ReturnWindowMinutes = 5;
		private const int IncantationSeconds = 5;
		private static readonly Point3D BloodLichLocation = new Point3D(4099, 3535, 20);

		private PlayerMobile m_Owner;
		private PlayerMobile m_Caster;
		private Point3D m_Pointer;
		private Map m_PointerMap;
		private int m_MinutesRemaining;
		private int m_SecondsRemaining;
		private int m_UpgradeLevel;
		private int m_ReturnMinutesRemaining;
		private bool m_IsAtBloodLich;
		private bool m_IsCasting;
		private bool m_MinuteTimerRegistered;

		public PlayerMobile Owner
		{
			get { return m_Owner; }
			set { m_Owner = value; }
		}

		public PlayerMobile Caster
		{
			get { return m_Caster; }
			set { m_Caster = value; }
		}

		public Point3D Pointer
		{
			get { return m_Pointer; }
			set { m_Pointer = value; }
		}

		public Map PointerMap
		{
			get { return m_PointerMap; }
			set { m_PointerMap = value; }
		}

		// Retained for the starter note generated by ShardGreeter.
		public Point3D MalasEntrance { get { return new Point3D( 2128, 1160, 0 ); } }
		public Point3D FeluccaEntrance { get { return new Point3D( 2965, 922, 0 ); } }
		public Point3D TerMurEntrance { get { return new Point3D( 882, 1531, 0 ); } }
		public Point3D TrammelEntrance { get { return new Point3D( 3240, 1704, 0 ); } }

		public int MinutesRemaining
		{
			get { return m_MinutesRemaining; }
			set { m_MinutesRemaining = value < 0 ? 0 : value; InvalidateProperties(); }
		}

		public int SecondsRemaining
		{
			get { return m_SecondsRemaining; }
			set { m_SecondsRemaining = value; }
		}

		[CommandProperty( AccessLevel.GameMaster )]
		public int UpgradeLevel
		{
			get { return m_UpgradeLevel; }
			set
			{
				if ( value < 0 )
					value = 0;
				else if ( value > MaximumUpgradeLevel )
					value = MaximumUpgradeLevel;

				m_UpgradeLevel = value;
				InvalidateProperties();
			}
		}

		[CommandProperty( AccessLevel.GameMaster )]
		public int CooldownMinutes
		{
			get
			{
				int cooldown = BaseCooldownMinutes - (m_UpgradeLevel * CooldownUpgradeMinutes);
				return cooldown < MinimumCooldownMinutes ? MinimumCooldownMinutes : cooldown;
			}
		}

		[CommandProperty( AccessLevel.GameMaster )]
		public int ReturnMinutesRemaining
		{
			get { return m_ReturnMinutesRemaining; }
			set { m_ReturnMinutesRemaining = value < 0 ? 0 : value; InvalidateProperties(); }
		}

		public bool IsAtBloodLich
		{
			get { return m_IsAtBloodLich; }
		}

		public bool CanUpgrade
		{
			get { return m_UpgradeLevel < MaximumUpgradeLevel; }
		}

		public override double DefaultWeight
		{
			get { return 0.1; }
		}

		public override int LabelNumber { get { return 1061204; } } // blood rune

		[Constructable]
		public BloodRune() : this( 1 )
		{
		}

		[Constructable]
		public BloodRune( int amount )
		{
			MinutesRemaining = 0;
			ReturnMinutesRemaining = 0;
			SecondsRemaining = IncantationSeconds;

			Stackable = false;
			Hue = 38;
			Amount = amount;
			ItemID = 0x1F14;
			Light = LightType.Circle150;
		}

		public BloodRune( Serial serial ) : base( serial )
		{
		}

		public override void Serialize( GenericWriter writer )
		{
			base.Serialize( writer );
			writer.Write( (int) 3 ); // version 3 adds the player ownership binding
			writer.Write( m_MinutesRemaining );
			writer.Write( m_UpgradeLevel );
			writer.Write( m_ReturnMinutesRemaining );
			writer.Write( m_IsAtBloodLich );
			writer.Write( m_Caster );
			writer.Write( m_Pointer );
			writer.Write( m_PointerMap );
			writer.Write( m_Owner );
		}

		public override void Deserialize( GenericReader reader )
		{
			base.Deserialize( reader );

			int version = reader.ReadInt();
			m_MinutesRemaining = reader.ReadInt();

			if ( version >= 2 )
			{
				m_UpgradeLevel = reader.ReadInt();
				m_ReturnMinutesRemaining = reader.ReadInt();
				m_IsAtBloodLich = reader.ReadBool();
				m_Caster = reader.ReadMobile() as PlayerMobile;
				m_Pointer = reader.ReadPoint3D();
				m_PointerMap = reader.ReadMap();

				if ( version >= 3 )
					m_Owner = reader.ReadMobile() as PlayerMobile;
				else
					m_Owner = m_Caster;
			}
			else
			{
				m_UpgradeLevel = 0;
				m_ReturnMinutesRemaining = 0;
				m_IsAtBloodLich = false;
				m_Caster = null;
				m_Owner = null;
				m_Pointer = Point3D.Zero;
				m_PointerMap = null;

				// Legacy runes used a 60-minute cooldown and stored 59 ticks.
				if ( m_MinutesRemaining > BaseCooldownMinutes )
					m_MinutesRemaining = BaseCooldownMinutes;
			}

			if ( m_UpgradeLevel < 0 || m_UpgradeLevel > MaximumUpgradeLevel )
				m_UpgradeLevel = 0;

			m_IsCasting = false;
			m_MinuteTimerRegistered = false;

			if ( m_IsAtBloodLich && m_Caster != null && m_ReturnMinutesRemaining > 0 )
			{
				m_Caster.Frozen = true;
				RegisterMinuteTimer();
			}
			else
			{
				m_IsAtBloodLich = false;
				m_ReturnMinutesRemaining = 0;
				m_Caster = null;

				if ( m_MinutesRemaining > 0 )
					RegisterMinuteTimer();
			}

			m_SecondsRemaining = IncantationSeconds;
			Light = LightType.Circle150;
		}

		public static BloodRune FindOwnedBy( PlayerMobile player )
		{
			if ( player == null )
				return null;

			if ( player.Backpack != null )
			{
				BloodRune backpackRune = player.Backpack.FindItemByType( typeof( BloodRune ) ) as BloodRune;

				if ( backpackRune != null && (backpackRune.Owner == null || backpackRune.Owner == player) )
				{
					if ( backpackRune.Owner == null )
						backpackRune.Owner = player;

					return backpackRune;
				}
			}

			if ( World.Items != null )
			{
				foreach ( Item item in World.Items.Values )
				{
					BloodRune rune = item as BloodRune;

					if ( rune != null && !rune.Deleted && rune.Owner == player )
						return rune;
				}
			}

			return null;
		}

		public override void GetProperties( ObjectPropertyList list )
		{
			base.GetProperties( list );
			list.Add( 1060658, "{0}\t{1}", "On use", "Teleport to the Blood Lich in Sosaria - cooldown begins on return" );  // ~1_val~: ~2_val~
			list.Add( 1060658, "{0}\t{1}", "Cooldown", CooldownMinutes.ToString() + " minutes (" + SoulForceUpgradeCost.ToString() + " SF per upgrade)" );  // ~1_val~: ~2_val~

			if ( m_IsAtBloodLich && ReturnMinutesRemaining > 0 )
				list.Add( 1060658, "{0}\t{1}", "Return window", ReturnMinutesRemaining.ToString() + " minutes" );  // ~1_val~: ~2_val~

			if ( MinutesRemaining > 0 )
				list.Add( 1060658, "{0}\t{1}", "Minutes remaining", MinutesRemaining.ToString() );  // ~1_val~: ~2_val~
		}

		private void RegisterMinuteTimer()
		{
			if ( !m_MinuteTimerRegistered )
			{
				OneTimeMinEvent.MinTimerTick += UpdateMinutesRemaining;
				m_MinuteTimerRegistered = true;
			}
		}

		private void UnregisterMinuteTimer()
		{
			if ( m_MinuteTimerRegistered )
			{
				OneTimeMinEvent.MinTimerTick -= UpdateMinutesRemaining;
				m_MinuteTimerRegistered = false;
			}
		}

		public void UpdateMinutesRemaining( object sender, EventArgs e )
		{
			if ( MinutesRemaining > 0 )
				--MinutesRemaining;

			if ( ReturnMinutesRemaining > 0 )
			{
				--ReturnMinutesRemaining;

				if ( ReturnMinutesRemaining == 0 )
					ReturnPlayer();
			}

			if ( MinutesRemaining == 0 && ReturnMinutesRemaining == 0 )
				UnregisterMinuteTimer();
		}

		public void PerformIncantation( object sender, EventArgs e )
		{
			if ( Caster != null && !Caster.Deleted && m_IsCasting )
			{
				if ( SecondsRemaining > 0 )
				{
					if ( !Caster.Mounted && Caster.Body.IsHuman )
						Caster.Animate( 239, 7, 1, true, false, 0 );

					Caster.PlaySound( 0x24A );
					Caster.Frozen = true;
					--SecondsRemaining;
				}
				else
				{
					SecondsRemaining = IncantationSeconds;
					m_IsCasting = false;
					Caster.PlaySound( 0x1FC );
					Caster.MoveToWorld( BloodLichLocation, Map.Trammel );
					Caster.Frozen = true;
					Caster.PlaySound( 0x1FC );
					m_IsAtBloodLich = true;
					ReturnMinutesRemaining = ReturnWindowMinutes;
					RegisterMinuteTimer();
					OneTimeSecEvent.SecTimerTick -= PerformIncantation;
				}
			}
			else
			{
				m_IsCasting = false;
				OneTimeSecEvent.SecTimerTick -= PerformIncantation;
			}
		}

		public bool UpgradeCooldown()
		{
			if ( !CanUpgrade || m_IsCasting )
				return false;

			++m_UpgradeLevel;
			InvalidateProperties();
			return true;
		}

		private void BeginCooldown()
		{
			if ( MinutesRemaining == 0 )
				MinutesRemaining = CooldownMinutes;

			RegisterMinuteTimer();
		}

		private void ReturnPlayer()
		{
			PlayerMobile player = Caster;
			Point3D returnPoint = Pointer;
			Map returnMap = PointerMap;

			m_Caster = null;
			m_Pointer = Point3D.Zero;
			m_PointerMap = null;
			m_IsAtBloodLich = false;
			ReturnMinutesRemaining = 0;

			if ( player != null && !player.Deleted )
			{
				player.Frozen = false;

				if ( returnMap != null && returnMap != Map.Internal && returnPoint != Point3D.Zero )
				{
					player.PlaySound( 0x1FC );
					player.MoveToWorld( returnPoint, returnMap );
					player.PlaySound( 0x1FC );
					player.SendMessage( "The blood rune returns you to where you began." );
				}
			}

			// The cooldown starts after either a manual or automatic return.
			BeginCooldown();
		}

		public override bool OnDragLift( Mobile from )
		{
			if ( !base.OnDragLift( from ) )
				return false;

			if ( m_Owner == null )
				m_Owner = from as PlayerMobile;

			return true;
		}

		public override void OnDoubleClick( Mobile from )
		{
			PlayerMobile player = from as PlayerMobile;

			if ( player == null )
				return;

			if ( player.Backpack == null || !IsChildOf( player.Backpack ) )
			{
				player.SendMessage( "The blood rune must be in your backpack to use it." );
			}
			else if ( m_IsAtBloodLich )
			{
				if ( Caster != player )
				{
					player.SendMessage( "This blood rune is bound to another soul until its return journey is complete." );
				}
				else if ( player.Map != Map.Trammel || !player.InRange( BloodLichLocation, 4 ) )
				{
					player.SendMessage( "You must remain near the Blood Lich to return with this rune." );
				}
				else
				{
					ReturnPlayer();
				}
			}
			else if ( m_IsCasting )
			{
				player.SendMessage( "The blood rune is already preparing its incantation." );
			}
			else if ( !player.SoulBound )
			{
				player.SendLocalizedMessage( 1061202 ); // You cannot bind your soul to this item
			}
			else if ( MinutesRemaining == 0 )
			{
				if ( player.Map == null || player.Map == Map.Internal )
				{
					player.SendMessage( "The blood rune does not work here" );
					return;
				}

				Region region = Region.Find( player.Location, player.Map );
				if ( region.IsPartOf( typeof( DungeonRegion ) ) )
				{
					player.SendMessage( "You cannot use this item in a dungeon." );
					return;
				}

				Caster = player;
				Pointer = player.Location;
				PointerMap = player.Map;
				m_IsCasting = true;
				SecondsRemaining = IncantationSeconds;
				if ( !player.Mounted && player.Body.IsHuman )
					player.Animate( 239, 7, 1, true, false, 0 );
				player.Frozen = true;
				player.SayTo( player, "namina uman..." );
				OneTimeSecEvent.SecTimerTick += PerformIncantation;
			}
			else
			{
				string plural = ( MinutesRemaining < 2 ) ? "minute" : "minutes";
				player.SendMessage( "You cannot use this rune at this time, you will be able to use it in " + MinutesRemaining.ToString() + " " + plural );
			}
		}

		public override void OnDelete()
		{
			if ( (m_IsAtBloodLich || m_IsCasting) && m_Caster != null && !m_Caster.Deleted )
				m_Caster.Frozen = false;

			m_IsAtBloodLich = false;
			m_IsCasting = false;
			UnregisterMinuteTimer();
			OneTimeSecEvent.SecTimerTick -= PerformIncantation;
			base.OnDelete();
		}
	}
}
